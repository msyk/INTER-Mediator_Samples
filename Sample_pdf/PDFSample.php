class PDFSample implements ProtocolProcessing
{

    public function processing(array $contextData, ?array $options): void
    {
        $prodId = $contextData[0]['id'];
        $prodName = $contextData[0]['name'];
        $unitPrice = $contextData[0]['unitprice'];
        $pFile = $contextData[0]['photofile'];
        $timestamp = new DateTime();
        $tsString = $timestamp->format("Y-m-d H:i:s");
        $fileName = "{$prodId}.pdf";

        $fontDirPath = dirname(__DIR__, 2) . '/vendor/tecnickcom/tc-lib-pdf-font/target/fonts/core/';
        $imageDirPath = dirname(__DIR__) . '/Sample_products/images/';
        try {
            if (PHP_VERSION_ID >= 80200) {
                define('K_PATH_FONTS', $fontDirPath);
                define('K_ALLOWED_PATHS', [$imageDirPath]);
                $pdf = new Tcpdf("mm", true, false, true,
                    fileOptions: ['allowedPaths' => [$fontDirPath, $imageDirPath]]);
                $bfont = $pdf->font->insert($pdf->pon, 'helvetica', '', 12);
                $page = $pdf->AddPage();
                $pdf->page->addContent($bfont['out']);
                $tableContents = "<tr><th style='width:150px'>Product ID:</th><td style='width:250px'>{$prodId}</td></tr>";
                $tableContents .= "<tr><th>Product Name:</th><td>{$prodName}</td></tr>";
                $tableContents .= "<tr><th>Unit Price:</th><td>{$unitPrice}</td></tr>";
                $tableContents .= "<tr><th>Today:</th><td>{$tsString}</td></tr>";
                $html = "<h1>PDF Generated by tc-lib-pdf</h1><table><tbody>{$tableContents}</tbody></table>";
                $html .= "<img style='width:300px;height:300px' src='{$imageDirPath}{$pFile}'>";
                $pdf->addHTMLCell(html: $html, posx: 15, posy: 20, width: 180); // HTML, from left page, from top page, with (mm)
//                $iid = $pdf->image->add("{$imageDirPath}{$pFile}");
//                $pdf->page->addContent($pdf->image->getSetImage(
//                    $iid, 15, 60, 150, 150, $page['height']));  // x, y, width, height, page height
                header("Content-Type: application/pdf");
                header("Content-Disposition: attachment; filename=\"{$fileName}\"");
                header('X-Frame-Options: SAMEORIGIN');
                $rawpdf = $pdf->getOutPDFString();
                $pdf->renderPDF($rawpdf);
            } else {
                // For TCPDF Ver.7
                define('K_ALLOWED_PATHS', [$imageDirPath]);
                $pdf = new TCPDF("P", "mm", "A4", true, "UTF-8");
                $pdf->setPrintHeader(false);
                $pdf->setPrintFooter(false);
                $pdf->SetMargins(0, 0, 0, 0);
                $pdf->AddPage();
                $pdf->setTextColor(100, 100, 100);
                $pdf->SetFont('', '', 14);
                $pdf->Text(40, 40, "Product ID: {$prodId}");
                $pdf->Text(40, 50, "Product Name: {$prodName}");
                $pdf->Text(40, 60, "Unit Price: {$unitPrice}");
                $pdf->Text(40, 70, "Today: {$tsString}");
                $pdf->Image(__DIR__ . "/../Sample_products/images/{$pFile}", 40, 80, 100);
                header("Content-Type: application/pdf");
                header("Content-Disposition: attachment; filename=\"{$fileName}\"");
                header('X-Frame-Options: SAMEORIGIN');
                $pdf->Output();
            }


        } catch (Exception $e) {
            error_log($e->getMessage());
            echo $e->getMessage();
        }
    }
}